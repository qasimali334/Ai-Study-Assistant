import { Router, Response } from 'express';
import axios from 'axios';
import { supabase } from '../config/supabase';
import { AuthenticatedRequest, requireAuth } from '../middlewares/auth';

const router = Router();

/**
 * @route   POST /api/exams/generate
 * @desc    Generate a syllabus exam (MCQs, short-answer, long-answer) and save it
 */
router.post('/generate', requireAuth, async (req: AuthenticatedRequest, res: Response) => {
  const userId = req.user?.id;
  const { document_id, exam_type, count } = req.body;

  if (!document_id || !exam_type || !['mcq', 'short', 'long'].includes(exam_type)) {
    return res.status(400).json({ error: 'document_id and exam_type ("mcq", "short", "long") are required.' });
  }

  try {
    // 1. Verify document exists and belongs to the authenticated user
    const { data: document, error: docErr } = await supabase
      .from('documents')
      .select('*')
      .eq('id', document_id)
      .eq('user_id', userId)
      .single();

    if (docErr || !document) {
      return res.status(404).json({ error: 'Document not found or access denied.' });
    }

    if (document.status !== 'indexed') {
      return res.status(400).json({ error: 'Document is still indexing. Please wait until status is "indexed".' });
    }

    // 2. Call FastAPI Python service to construct exam questions
    const fastapiUrl = process.env.PYTHON_SERVICE_URL || 'http://127.0.0.1:8000';
    const response = await axios.post(`${fastapiUrl}/generate-exam`, {
      document_id,
      exam_type,
      count: count || 5
    });

    const examQuestions = response.data.questions;
    if (!examQuestions || !Array.isArray(examQuestions)) {
      throw new Error('Invalid quiz format generated by AI engine.');
    }

    // 3. Save the generated exam into Supabase
    const { data: exam, error: insertErr } = await supabase
      .from('exams')
      .insert({
        user_id: userId,
        document_id,
        title: `Exam - ${document.title} (${exam_type.toUpperCase()})`,
        exam_type,
        questions: examQuestions
      })
      .select()
      .single();

    if (insertErr || !exam) {
      throw new Error(`Failed to save exam: ${insertErr?.message}`);
    }

    return res.status(200).json(exam);

  } catch (err: any) {
    console.error('Exam generation error:', err.message || err);
    let errorMessage = 'An error occurred during exam generation.';
    if (err.code === 'ECONNREFUSED' || err.message?.includes('ECONNREFUSED')) {
      errorMessage = 'AI Exam Generation Service is offline. Please make sure the Python FastAPI backend is running on port 8000.';
    } else if (err.message) {
      errorMessage = err.message;
    }
    return res.status(500).json({ error: errorMessage });
  }
});

/**
 * @route   GET /api/exams
 * @desc    Fetch all exams created by the student
 */
router.get('/', requireAuth, async (req: AuthenticatedRequest, res: Response) => {
  try {
    const { data: exams, error } = await supabase
      .from('exams')
      .select('*, documents(title)')
      .eq('user_id', req.user?.id)
      .order('created_at', { ascending: false });

    if (error) {
      return res.status(400).json({ error: error.message });
    }

    return res.status(200).json(exams);
  } catch (err) {
    return res.status(500).json({ error: 'Internal server error fetching exams.' });
  }
});

/**
 * @route   GET /api/exams/:id
 * @desc    Fetch single exam details
 */
router.get('/:id', requireAuth, async (req: AuthenticatedRequest, res: Response) => {
  try {
    const { data: exam, error } = await supabase
      .from('exams')
      .select('*, documents(title)')
      .eq('id', req.params.id)
      .eq('user_id', req.user?.id)
      .single();

    if (error || !exam) {
      return res.status(404).json({ error: 'Exam not found or unauthorized.' });
    }

    return res.status(200).json(exam);
  } catch (err) {
    return res.status(500).json({ error: 'Internal server error fetching exam details.' });
  }
});

export default router;
